#!/usr/bin/env bash
# Builds a Supabase demo git repo with one base release and five candidate
# releases. v1 is the todo list from Supabase's nextjs-todo-list example, plus
# a remind edge function and a pg_cron job that purges past reminders:
#   v2-expand   adds todos.priority (safe)
#   v2-rename   renames todos.is_complete to done (breaks v1's update)
#   v2-rls      lets users add todos only to their own lists (breaks v1's
#               inserts, through row-level security)
#   v2-untested drops todos.inserted_at, which only untested code reads (a
#               schema probe catches it, replay doesn't)
#   v2-edge     adds reminders.channel, required, and sets it in the remind
#               function (breaks the workers still running the old function)
#
# The repo uses the scripts in examples/supabase. Building it runs npm to
# write package-lock.json.
#
# Usage: make-supabase-demo.sh DIR
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
dir=${1:?usage: make-supabase-demo.sh DIR}
mkdir -p "$dir"
cd "$dir"
git init -q
git checkout -q -b main

mkdir -p lib scripts supabase/functions/remind supabase/migrations
cp "$here/supabase/migcheck-migrate.sh" "$here/supabase/migcheck-stack.mjs" scripts/

cat > .gitignore <<'EOF'
node_modules/
supabase/.temp/
EOF

cat > package.json <<'EOF'
{
  "name": "migcheck-supabase-demo",
  "private": true,
  "type": "module",
  "scripts": {
    "test": "node test.mjs"
  },
  "devDependencies": {
    "@supabase/supabase-js": "2.117.3",
    "supabase": "2.120.0"
  }
}
EOF
npm install --package-lock-only --silent

cat > supabase/config.toml <<'EOF'
project_id = "migcheck-supabase-demo"
EOF

# From https://github.com/supabase/supabase/tree/master/examples/todo-list/nextjs-todo-list
# (Apache-2.0).
cat > supabase/migrations/20230712094349_init.sql <<'EOF'
create table todos (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users not null,
  task text check (char_length(task) > 3),
  is_complete boolean default false,
  inserted_at timestamp with time zone default timezone('utc'::text, now()) not null
);
alter table todos enable row level security;
create policy "Individuals can create todos." on todos for
    insert with check (auth.uid() = user_id);
create policy "Individuals can view their own todos. " on todos for
    select using (auth.uid() = user_id);
create policy "Individuals can update their own todos." on todos for
    update using (auth.uid() = user_id);
create policy "Individuals can delete their own todos." on todos for
    delete using (auth.uid() = user_id);
EOF

cat > supabase/migrations/20230801000000_add_reminders.sql <<'EOF'
create table reminders (
  id bigint generated by default as identity primary key,
  todo_id bigint references todos on delete cascade not null,
  remind_at timestamp with time zone not null
);
-- Only the remind function, as service_role, reads and writes reminders.
alter table reminders enable row level security;

create extension if not exists pg_cron with schema pg_catalog;
select cron.schedule('purge-past-reminders', '0 3 * * *',
  $$delete from reminders where remind_at < now() - interval '30 days'$$);
EOF

cat > supabase/functions/remind/index.ts <<'EOF'
// Sets a reminder on one of the caller's todos.
import { createClient } from 'npm:@supabase/supabase-js@2.117.3'

const url = Deno.env.get('SUPABASE_URL')!

Deno.serve(async (req) => {
  const { todo_id, remind_at } = await req.json()

  // Checks that the caller owns the todo, through RLS.
  const caller = createClient(url, Deno.env.get('SUPABASE_ANON_KEY')!, {
    global: { headers: { Authorization: req.headers.get('Authorization')! } },
    auth: { persistSession: false },
  })
  const { data: todo, error } = await caller.from('todos').select('id').eq('id', todo_id).maybeSingle()
  if (error) return Response.json({ error: error.message }, { status: 500 })
  if (!todo) return Response.json({ error: 'todo not found' }, { status: 404 })

  const admin = createClient(url, Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!, { auth: { persistSession: false } })
  const { data, error: insertError } = await admin.from('reminders').insert({ todo_id, remind_at }).select().single()
  if (insertError) return Response.json({ error: insertError.message }, { status: 500 })
  return Response.json(data)
})
EOF

cat > lib/todos.mjs <<'EOF'
// The queries from the example's components/TodoList.tsx.

export async function fetchTodos(supabase) {
  const { data, error } = await supabase.from('todos').select('*').order('id', { ascending: true })
  if (error) throw error
  return data
}

export async function addTodo(supabase, user, task) {
  const { data, error } = await supabase.from('todos').insert({ task, user_id: user.id }).select().single()
  if (error) throw error
  return data
}

export async function toggleTodo(supabase, todo) {
  const { data } = await supabase
    .from('todos')
    .update({ is_complete: !todo.is_complete })
    .eq('id', todo.id)
    .throwOnError()
    .select()
    .single()
  return data
}

export async function deleteTodo(supabase, id) {
  await supabase.from('todos').delete().eq('id', id).throwOnError()
}

export async function remind(supabase, todo, remindAt) {
  const { data, error } = await supabase.functions.invoke('remind', { body: { todo_id: todo.id, remind_at: remindAt } })
  if (error) throw error
  return data
}

// The tests don't call this.
export async function recentTodos(supabase) {
  const { data, error } = await supabase.from('todos').select('id, task, inserted_at').order('inserted_at', { ascending: false }).limit(5)
  if (error) throw error
  return data
}
EOF

cat > test.mjs <<'EOF'
// Stands in for the app's test suite: signs up two users and runs the app's
// queries as each of them. Like many test suites, it misses a query: nothing
// here calls recentTodos.
import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import { createClient } from '@supabase/supabase-js'
import { fetchTodos, addTodo, toggleTodo, deleteTodo, remind } from './lib/todos.mjs'

async function signUp(name) {
  const supabase = createClient(process.env.SUPABASE_URL, process.env.SUPABASE_ANON_KEY, {
    auth: { persistSession: false },
  })
  const { data, error } = await supabase.auth.signUp({
    email: `${name}-${randomUUID()}@example.com`,
    password: 'correct-horse-battery-staple',
  })
  if (error) throw error
  return { supabase, user: data.user }
}

const ada = await signUp('ada')
const bob = await signUp('bob')

const todo = await addTodo(ada.supabase, ada.user, 'Write the report')
assert.equal(todo.is_complete, false)
await addTodo(ada.supabase, ada.user, 'Send the invoice')
await addTodo(bob.supabase, bob.user, 'Book the venue')

assert.equal((await fetchTodos(ada.supabase)).length, 2)
assert.equal((await fetchTodos(bob.supabase)).length, 1, "RLS hides Ada's todos from Bob")

const reminder = await remind(ada.supabase, todo, '2030-01-01T09:00:00Z')
assert.equal(reminder.todo_id, todo.id)
await assert.rejects(remind(bob.supabase, todo, '2030-01-01T09:00:00Z'), "Bob can't set reminders on Ada's todos")

const toggled = await toggleTodo(ada.supabase, todo)
assert.equal(toggled.is_complete, true)

await deleteTodo(ada.supabase, todo.id)
assert.equal((await fetchTodos(ada.supabase)).length, 1)
console.log('ok')
EOF

git add -A && git commit -q -m "v1" && git tag v1

git checkout -q -b expand v1
cat > supabase/migrations/20231001000000_add_priority.sql <<'EOF'
alter table todos add column priority smallint;
EOF
git add -A && git commit -q -m "v2: add priority" && git tag v2-expand

git checkout -q -b rename v1
cat > supabase/migrations/20231001000000_rename_is_complete.sql <<'EOF'
alter table todos rename column is_complete to done;
EOF
sed -i 's/is_complete/done/g' lib/todos.mjs test.mjs
git add -A && git commit -q -m "v2: rename is_complete to done" && git tag v2-rename

git checkout -q -b rls v1
cat > supabase/migrations/20231001000000_add_lists.sql <<'EOF'
create table lists (
  id bigint generated by default as identity primary key,
  owner uuid references auth.users not null default auth.uid(),
  name text not null
);
alter table lists enable row level security;
create policy "Owners can manage their lists." on lists
    using (auth.uid() = owner) with check (auth.uid() = owner);

alter table todos add column list_id bigint references lists;
drop policy "Individuals can create todos." on todos;
create policy "Individuals can create todos in their lists." on todos for
    insert with check (auth.uid() = user_id and list_id in (select id from lists where owner = auth.uid()));
EOF
git add -A && git commit -q -m "v2: add lists, and require one for new todos" && git tag v2-rls

git checkout -q -b untested v1
cat > supabase/migrations/20231001000000_drop_inserted_at.sql <<'EOF'
alter table todos drop column inserted_at;
EOF
git add -A && git commit -q -m "v2: drop inserted_at" && git tag v2-untested

git checkout -q -b edge v1
cat > supabase/migrations/20231001000000_add_reminder_channel.sql <<'EOF'
alter table reminders add column channel text not null check (channel in ('email', 'push'));
EOF
sed -i "s/insert({ todo_id, remind_at })/insert({ todo_id, remind_at, channel: 'email' })/" supabase/functions/remind/index.ts
git add -A && git commit -q -m "v2: require a channel for reminders" && git tag v2-edge

git checkout -q main
echo "Supabase demo repo ready at $dir (tags: v1, v2-expand, v2-rename, v2-rls, v2-untested, v2-edge)"
